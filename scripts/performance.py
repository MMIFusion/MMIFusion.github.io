"""Deterministic shared bundles and display-only media substitutions."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSS = ['style.css','portal.css','experience.css','community.css']
JS = ['metrics-core.js','app.js','calendar-core.js','portal.js','experience.js','community-core.js','community.js']

def bundles():
    for names,output,separator in [(CSS,'site.css','\n'),(JS,'site.js','\n;\n')]:
        content=separator.join('/* Source: '+name+' */\n'+(ROOT/'assets'/name).read_text() for name in names)
        (ROOT/'assets'/output).write_text('/* Generated by scripts/performance.py; edit the named source files. */\n'+content+'\n')

def images(document):
    previews=json.loads((ROOT/'data/image-previews.json').read_text())
    def image(match):
        tag=match.group()
        source=re.search(r'\bsrc="([^"]+)"',tag)
        if not source: return tag
        path=source.group(1)
        # Original images remain the full-resolution source in dataset dialogs.
        if path in previews and '原始示例图' not in tag:
            item=previews[path]
            tag=tag.replace('src="'+path+'"','src="'+item['src']+'" data-original-src="'+path+'"')
            if not re.search(r'\bwidth=',tag): tag=tag[:-1]+f' width="{item["width"]}" height="{item["height"]}">'
        if 'decoding=' not in tag: tag=tag[:-1]+' decoding="async">'
        if path.startswith('assets/qr/') and 'loading=' not in tag: tag=tag[:-1]+' loading="lazy">'
        return tag
    document=re.sub(r'<img\b[^>]*>',image,document)
    document=document.replace('<link rel="icon" href="assets/avatar.png" type="image/png">','<link rel="icon" href="assets/favicon.png" type="image/png">')
    return document.replace('<link rel="apple-touch-icon" href="assets/avatar.png">','<link rel="apple-touch-icon" href="assets/apple-touch-icon.png">')
